window.ArisanCountries.getFlagCode = function getFlagCode(countryName) {
    const row = window.ArisanCountries.find(c => c.name === countryName);
    return row ? row.flag : '';
};

window.ArisanCountries.FLAGCDN_BASE = 'https://flagcdn.com';

/** Ukuran standar flagcdn — satu sumber untuk seluruh app */
window.ArisanCountries.FLAG_SIZE = {
    bracket: 40,
    preview: 80,
    celebration: 320,
};

window.ArisanCountries.getFlagUrlByCode = function getFlagUrlByCode(code, width) {
    const c = String(code || '').trim().toLowerCase();
    if (!c || /^https?:\/\//i.test(c)) return '';
    const w = width || window.ArisanCountries.FLAG_SIZE.bracket;
    return window.ArisanCountries.FLAGCDN_BASE + '/w' + w + '/' + c + '.png';
};

/** Ekstrak kode negara dari URL flagcdn atau kode mentah (mis. "ar"). */
window.ArisanCountries.parseFlagCode = function parseFlagCode(value) {
    const s = String(value || '').trim();
    if (!s) return '';
    const fromUrl = s.match(/flagcdn\.com\/w\d+\/([a-z0-9-]+)\.png/i);
    if (fromUrl) return fromUrl[1].toLowerCase();
    if (/^[a-z0-9-]{2,12}$/i.test(s)) return s.toLowerCase();
    return '';
};

/** URL bendera: kode/URL flagcdn → flagcdn; URL custom (club) → as-is. */
window.ArisanCountries.resolveFlagUrl = function resolveFlagUrl(flagOrCode, width) {
    const s = String(flagOrCode || '').trim();
    if (!s) return '';
    if (/^https?:\/\//i.test(s) && !/flagcdn\.com/i.test(s)) return s;
    const w = width || window.ArisanCountries.FLAG_SIZE.bracket;
    const code = window.ArisanCountries.parseFlagCode(s);
    if (code) return window.ArisanCountries.getFlagUrlByCode(code, w);
    return s;
};

window.ArisanCountries.getFlagUrl = function getFlagUrl(countryName, width) {
    const code = window.ArisanCountries.getFlagCode(countryName);
    return code ? window.ArisanCountries.getFlagUrlByCode(code, width) : '';
};

/** Resolusi tinggi untuk floating celebration effect. */
window.ArisanCountries.getCelebrationFlagUrl = function getCelebrationFlagUrl(flagSrcOrCode) {
    const s = String(flagSrcOrCode || '').trim();
    if (!s) return '';
    if (/^https?:\/\//i.test(s) && !/flagcdn\.com/i.test(s)) return s;
    const code = window.ArisanCountries.parseFlagCode(s);
    if (code) {
        return window.ArisanCountries.getFlagUrlByCode(code, window.ArisanCountries.FLAG_SIZE.celebration);
    }
    return s;
};
